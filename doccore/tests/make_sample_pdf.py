"""Generates tests/data/sample_pdf.pdf — a third-party (PyMuPDF) PDF fixture.

DocCore's own PDF writer is verified by verify_output.py; this fixture exists to
exercise the *reader* and the PDF -> DOCX/XLSX/PPTX reconstructor on a file that
DocCore did not produce, per docs/01 F-302 "第三方打印驱动生成的文本型 PDF".

Layout:
  page 1  A4 portrait  title + two body paragraphs + ruled 4x3 table + image
  page 2  A4 portrait  full-width heading + two text columns (reading order)
  page 3  A4 portrait  table with no ruling lines (column alignment heuristic)
  page 4  A4 portrait  full-page image only (scanned page, no text layer)
"""

import os
import sys

import fitz

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "data", "sample_pdf.pdf")

A4 = (595.28, 841.89)


def make_image_png(width=96, height=72):
    """A small deterministic PNG: diagonal grey ramp with a black frame."""
    pix = fitz.Pixmap(fitz.csRGB, fitz.IRect(0, 0, width, height), False)
    samples = bytearray(pix.samples_mv)
    for y in range(height):
        for x in range(width):
            v = (x * 255 // max(1, width - 1) + y * 255 // max(1, height - 1)) // 2
            edge = x < 2 or y < 2 or x >= width - 2 or y >= height - 2
            i = (y * width + x) * 3
            if edge:
                samples[i] = samples[i + 1] = samples[i + 2] = 0
            else:
                samples[i] = samples[i + 1] = samples[i + 2] = v
    pix.samples_mv[:] = bytes(samples)
    return pix.tobytes("png")


def page_one(doc, png):
    page = doc.new_page(width=A4[0], height=A4[1])
    page.insert_text((72, 80), "DocCore PDF Rebuild Fixture", fontsize=24, fontname="helv")
    page.insert_text(
        (72, 118), "This page is generated by PyMuPDF, not by DocCore.", fontsize=11
    )
    page.insert_text(
        (72, 134), "It exercises text, a ruled table and an image.", fontsize=11
    )
    page.insert_text((72, 150), "中文一行，用来验证 ToUnicode 反查。", fontsize=11,
                     fontname="china-s")

    # Ruled 4x3 table: x edges 72/184/296/408/520, y edges 200/240/280/320.
    xs = [72, 184, 296, 408, 520]
    ys = [200, 240, 280, 320]
    for y in ys:
        page.draw_line((xs[0], y), (xs[-1], y), color=(0, 0, 0), width=0.8)
    for x in xs:
        page.draw_line((x, ys[0]), (x, ys[-1]), color=(0, 0, 0), width=0.8)

    rows = [
        ["Region", "Q1", "Q2", "Q3"],
        ["North", "10", "20", "30"],
        ["South", "40", "50", "60"],
    ]
    for r, row in enumerate(rows):
        for c, text in enumerate(row):
            page.insert_text((xs[c] + 6, ys[r] + 26), text, fontsize=11)

    rect = fitz.Rect(72, 360, 72 + 96, 360 + 72)
    page.insert_image(rect, stream=png)
    page.insert_text((72, 460), "Caption under the image.", fontsize=11)


def page_two(doc):
    page = doc.new_page(width=A4[0], height=A4[1])
    page.insert_text((72, 80), "Two Column Page", fontsize=18, fontname="helv")
    left = [
        "Left one: alpha beta gamma delta.",
        "Left two: epsilon zeta eta theta.",
        "Left three: iota kappa lambda mu.",
        "Left four: nu xi omicron pi.",
    ]
    right = [
        "Right one: rho sigma tau upsilon.",
        "Right two: phi chi psi omega.",
        "Right three: second column continues.",
        "Right four: reading order must follow.",
    ]
    for i, text in enumerate(left):
        page.insert_text((72, 120 + i * 18), text, fontsize=11)
    for i, text in enumerate(right):
        page.insert_text((316, 120 + i * 18), text, fontsize=11)


def page_three(doc):
    page = doc.new_page(width=A4[0], height=A4[1])
    page.insert_text((72, 80), "Aligned Table Page", fontsize=18, fontname="helv")
    # No ruling lines: columns are aligned by x position only.
    cols = [72, 220, 320]
    rows = [
        ("Item", "Qty", "Price"),
        ("Widget", "3", "4.50"),
        ("Gadget", "2", "9.25"),
        ("Doohickey", "1", "12.00"),
    ]
    for r, row in enumerate(rows):
        for c, text in enumerate(row):
            page.insert_text((cols[c], 130 + r * 20), text, fontsize=11)


def page_four(doc):
    page = doc.new_page(width=A4[0], height=A4[1])
    # A single image covering the whole page, no text at all: scanned page.
    pix = fitz.Pixmap(fitz.csGRAY, fitz.IRect(0, 0, 200, 280), False)
    samples = bytearray(pix.samples_mv)
    for i in range(len(samples)):
        samples[i] = 255 if (i // 200) % 40 else 32
    pix.samples_mv[:] = bytes(samples)
    page.insert_image(fitz.Rect(0, 0, A4[0], A4[1]), stream=pix.tobytes("png"))


def main():
    os.makedirs(os.path.join(HERE, "data"), exist_ok=True)
    doc = fitz.open()
    png = make_image_png()
    page_one(doc, png)
    page_two(doc)
    page_three(doc)
    page_four(doc)
    doc.set_metadata({"title": "sample_pdf", "producer": "PyMuPDF fixture"})
    doc.save(OUT, deflate=True, garbage=3)
    doc.close()
    print("wrote %s (%d bytes)" % (OUT, os.path.getsize(OUT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
